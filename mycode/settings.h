/**
 * @file    settings.h
 * @brief   设置界面接口声明
 *
 * =====================================================================
 * 一、这个界面提供什么
 * =====================================================================
 *   四项设置，全部即时生效、不落盘（重启回到默认值）：
 *     ① 屏幕亮度   滑条 0~100，直接写背光 sysfs
 *     ② 自动亮度   开关；开启后每 1 秒读环境光，自动调背光
 *     ③ 体感校准   按钮，调用 imu_calibrate() 把当前姿态当零点
 *     ④ 关于       版本号文字（纯展示）
 *
 * =====================================================================
 * 二、涉及哪些硬件
 * =====================================================================
 *   背光      /sys/class/backlight/backlight/{brightness,max_brightness}
 *             ★ 注意极性是反的：写 255 最暗、写 0 最亮。
 *               所以代码里统一按"百分比越大越亮"来思考，
 *               在真正写文件前才做一次反相（宏 BACKLIGHT_INVERTED）。
 *
 *   BH1750    /sys/bus/iio/devices/iio:device2/in_illuminance_input
 *             （和 sensor.c 读的是同一个传感器。
 *               本模块为了不依赖 sensor.c 而自己写了一份读取代码 ——
 *               功能重复，见 settings.c 里 read_illuminance_lux 的说明）
 *
 *   MPU6050   通过 imu.h 的 imu_calibrate() 间接使用
 *
 * =====================================================================
 * 三、自动亮度是怎么工作的
 * =====================================================================
 *   开关注册一个 1000ms 的 LVGL 定时器，每拍做三件事：
 *     读 lux → 映射成百分比 → 写背光 + 同步滑条和百分比标签
 *
 *   映射曲线（不是线性的，做了上下限保护）：
 *     lux ≤ 10      → 30%    （再暗也不低于 30%，否则屏幕看不清）
 *     lux ≥ 1000    → 100%
 *     其它          → 30 + (lux-10)×70/990   （10~1000 lux 线性映射到 30~100%）
 *
 *   开自动时会把滑条置为 DISABLED（禁止手动拖），
 *   关自动时恢复可拖 —— 避免"自动在调、用户也在拖"互相打架。
 *
 * =====================================================================
 * 四、屏幕指针的生命周期
 * =====================================================================
 *   settings_screen 进来时创建，点返回时删除并置 NULL。
 *   因为返回时也顺手删掉了自动亮度定时器，
 *   所以不存在"定时器还在跑、但它操作的控件已经没了"的悬空访问。
 */
#ifndef __SETTINGS_H__
#define __SETTINGS_H__

/* 设置界面屏。
 * 由 ui_settings_init 赋值，由返回回调删除并置 NULL。
 * 声明成 extern 是为了让 main_interface.c 等外部模块能读到/清理它。 */
extern lv_obj_t * settings_screen;   // 设置界面屏（全局）

/**
 * 创建并返回设置屏幕对象。
 *
 * 做了三件事：
 *   1. 取两档中文字体（24 标题 / 22 正文）；
 *   2. 创建滑条、百分比标签、开关、校准按钮、版本文字，
 *      并把滑条和百分比标签存进**模块内的 static 全局**
 *      （因为自动亮度定时器回调需要访问它们，而回调只能拿到定时器参数）；
 *   3. lv_screen_load(scr) 切到本屏，并把屏幕存进 settings_screen。
 *
 * 副作用警告：内部已经 lv_screen_load()，调用方不需要再切屏
 *   （属于"创建即显示"风格，和 game_center / chat_ui 一致）。
 *
 * 重复调用会创建出第二屏且旧的没人删，所以调用方应先判 NULL。
 *
 * @return 新建的屏幕对象
 */
lv_obj_t * ui_settings_init(void);

#endif
