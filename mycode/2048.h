/**
 * @file    2048.h
 * @brief   2048 体感版游戏界面接口声明
 *
 * =====================================================================
 * 一、玩法
 * =====================================================================
 *   经典 2048，4×4 棋盘，瓷砖用 BMP 图片显示（图片名 = 数字，如 2.bmp）：
 *     - 两个相同数字合并时翻倍，得分累加合并后的数值；
 *     - 每次有效移动后在随机空格补一个新方块（2 或 4）；
 *     - 出现 2048 → 成功（可选"继续"冲更高分）；
 *     - 棋盘填满且无法再合并 → 失败。
 *
 *   两种控制模式（开始前二选一）：
 *     ① 滑动模式：在屏幕上按下拖动，松开时按滑动方向移动（触摸）
 *     ② 体感模式：倾斜开发板触发移动（每 100ms 检测一次）
 *
 * =====================================================================
 * 二、本头文件只暴露一个函数 —— 这里有个设计上的不对称
 * =====================================================================
 *   2048.c **不自己保存屏幕指针**，而是由调用方保存：
 *
 *     // game_center.c 里是这么用的：
 *     if(game_2048_screen == NULL)
 *         game_2048_screen = ui_2048_init();    // ← 调用方接住返回值
 *
 *   而 game_2048_screen 这个全局变量声明在 **game_center.h** 里，
 *   不在这里。对比一下其他游戏：
 *     ball.h   声明 ball_screen，ball.c 自己赋值  → 模块自管
 *     2048.h   什么都不声明，2048.c 只 return   → 调用方管
 *
 *   两种风格混用，是历史原因造成的（2048 是最早写的模块）。
 *   后果：如果你看到 `game_2048_screen` 却在本文件里找不到它，
 *   要去 game_center.h 找 —— 这一点在读代码时容易被绊住。
 *   而 2048.c 的返回回调 to_game_center_cb 又会把它删掉并置 NULL。
 *
 * =====================================================================
 * 三、依赖
 * =====================================================================
 *   本头文件没有 include lvgl.h，但用到 lv_obj_t* ——
 *   所以**调用方必须先 include lvgl.h**（game_center.c 已经这么做了）。
 *   2048.c 另外还依赖 imu.h（体感）和 game_center.h（返回）。
 */
#ifndef __2048_H__
#define __2048_H__

/* 创建并返回 2048 游戏屏幕对象
 *
 * 做了这些事：
 *   1. 取 3 档中文字体（28 标题 / 18 正文 / 36 结束大字）；
 *   2. init_2048_game() 清空棋盘、分数归零、随机放两个初始方块；
 *   3. 创建棋盘底板 + 16 个瓷砖图像控件 + 模式选择 UI + 结束提示/按钮；
 *   4. 在全屏窗口上注册触摸滑动回调（滑动模式用，靠 game_mode 过滤）；
 *      ★ 体感定时器**不在这里创建**，等用户选了「体感模式」才启动；
 *   5. lv_screen_load(scr) 切到本屏。
 *
 * 副作用警告：内部已经 lv_screen_load()，调用方不需要再切屏。
 * 且**不赋值任何全局指针** —— 屏幕指针由调用方自己接住（见上面说明）。
 *
 * @return 新建的屏幕对象
 */
lv_obj_t * ui_2048_init(void);

#endif
