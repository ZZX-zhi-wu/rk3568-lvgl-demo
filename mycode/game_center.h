/**
 * @file    game_center.h
 * @brief   体感游戏中心界面接口声明
 *
 * =====================================================================
 * 一、这一层是干什么的
 * =====================================================================
 *   桌面 ──▶ [游戏中心] ──▶ 2048 / 重力滚球 / 体感贪吃蛇
 *
 *   游戏中心是"桌面"和"具体游戏"之间的中间层菜单：
 *   桌面上只有一个"游戏中心"入口，进去之后才是三个游戏卡片。
 *   这样做的好处是以后加游戏只改这一个文件，不用动桌面布局。
 *
 * =====================================================================
 * 二、两个全局屏指针（本文件的核心，搞错会段错误）
 * =====================================================================
 *   select_game_screen  游戏中心屏。从桌面进来时创建，
 *                       点某个游戏或点返回时会 lv_obj_delete 掉并置 NULL，
 *                       下次再进来重新创建 —— 保证卡片状态是干净的。
 *
 *   game_2048_screen    2048 游戏屏。它比较特殊：
 *                       2048.c 返回时会**删掉自己**，所以这里必须保留
 *                       这个全局指针，才能在下次进入时判断"还要不要重新建"。
 *                       （如果这里不置 NULL，下次进来会拿已释放的地址去用 → 崩）
 *
 *   一句话对照：
 *     select_game_screen  进来之前 NULL、离开时回 NULL
 *     game_2048_screen    由 2048.c 自己管生命周期，本文件只负责转交
 *
 * =====================================================================
 * 三、依赖关系
 * =====================================================================
 *   本头文件没有 include lvgl.h，但用到 lv_obj_t*，
 *   所以**调用方必须先 include lvgl.h**。
 *   实际使用场景（main_interface.c）已经这么做了。
 */
#ifndef __GAME_CENTER_H__
#define __GAME_CENTER_H__

/* 2048 游戏屏。
 * 由本模块的 to_2048_screen_cb 创建/转交，由 2048.c 在自己的返回回调里删除。
 * 声明成 extern 是因为要跨文件共享：2048.c 也要能看到并置 NULL。 */
extern lv_obj_t * game_2048_screen;    // 2048 游戏屏（2048.c 返回时会删它）

/* 游戏中心屏。
 * 桌面点进来时创建并赋值，点返回或点任一游戏时删除并置 NULL。
 * 注意：本模块内每次切走都会删掉它，所以不存在"复用旧屏"的情况。 */
extern lv_obj_t * select_game_screen;   // 游戏中心屏（全局，返回时复用）

/**
 * 创建并返回游戏中心屏幕对象。
 *
 * 做了三件事：
 *   1. 加载 3 档中文字体（24 标题 / 22 卡片名 / 14 描述）；
 *   2. 铺背景图 + 返回按钮 + 标题 + "陀螺仪已就绪"胶囊 + 3 张游戏卡片；
 *   3. lv_screen_load(scr) 立刻切到本屏，并把屏幕存进 select_game_screen。
 *
 * 副作用警告：本函数内部已经调了 lv_screen_load()，
 *   调用方**不需要**再切屏，直接返回即可（和 chat_ui 的 ui_chat_conn_init 一样，
 *   属于"创建即显示"的风格）。
 *
 * 重复调用会创建出第二个游戏中心屏（旧的没人删 → 内存泄漏），
 *   所以调用方必须先判 `if(select_game_screen == NULL)`。
 *
 * @return 新建的屏幕对象
 */
lv_obj_t * ui_select_game_screen(void);

#endif
