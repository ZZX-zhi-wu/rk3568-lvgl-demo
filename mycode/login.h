/**
 * @file    login.h
 * @brief   登录界面接口声明
 *
 * =====================================================================
 * 一、模块定位
 * =====================================================================
 *   整个项目的**第一个界面**。main.c 上电后先调 login()，
 *   用户在这里登录（或点"游客模式"），成功后跳到桌面 Launcher。
 *
 *   启动流程：
 *     main.c → login() → [登录页] → ui_select_app_screen() → [桌面]
 *
 * =====================================================================
 * 二、对外只暴露一个函数
 * =====================================================================
 *   本模块没有全局屏指针 —— 因为登录页**用完就不再回去**了
 *   （返回桌面不需要回到登录页），所以没必要让外部能引用它。
 *   代价是：创建出来的 login_screen 没有任何全局指针指向它，
 *   程序运行期间**永远不会被删除**（详见 login.c 的说明）。
 *
 * =====================================================================
 * 三、一个不太好的地方：本头文件 include 了太多无关内容
 * =====================================================================
 *   下面这一大串 include（lv_demos.h / pthread.h / time.h /
 *   lv_examples.h / 2048.h / album.h）其实登录界面一个都用不到，
 *   它们都是"复制粘贴时一起带过来"的。
 *
 *   为什么不好：
 *     任何 include 了 login.h 的文件，都会被动地把这 6 个头文件
 *     也拉进来（编译变慢），而且会造成虚假的依赖关系 ——
 *     比如看起来 login 模块依赖 2048 模块，其实并不依赖。
 *
 *   为什么不改：本工程头文件数量少、编译规模小，实际影响可以忽略；
 *     而删 include 有连带风险（某些类型可能靠它间接引入）。
 *     知道这是个可以优化点即可 —— 答辩被问到"你的头文件设计有什么问题"
 *     时，这就是一个好答案。
 */
#ifndef __LOGIN_H__
#define __LOGIN_H__

#include "lvgl/lvgl.h"
#include "lvgl/demos/lv_demos.h"
#include <unistd.h>
#include <pthread.h>
#include <time.h>
#include "lvgl/examples/lv_examples.h"
#include <stdio.h>
#include "main_interface.h"
#include "2048.h"
#include "album.h"

/**
 * 登录界面入口函数（供 main.c 调用）。
 *
 * 内部会创建并加载登录屏（"创建即显示"）。
 * 注意本函数**不带返回值**：因为登录成功后的跳转是在
 * 按钮回调里通过全局 select_app_screen 完成的，不需要返回给 main。
 *
 * 可重复调用，但每次都会新建一屏且不释放旧的，
 * 所以正常情况下只应该在 main.c 里调一次。
 */
void login(void);

#endif
