/**
 * @file    imu.c
 * @brief   IMU 数据层（体感游戏用）
 *
 * =====================================================================
 * 一、工作原理：Linux 的 IIO 子系统 + sysfs
 * =====================================================================
 *   板子上的 MPU6050 由一个内核驱动管理，驱动会把它挂到 IIO
 *   (Industrial I/O) 子系统下，注册成 iio:device1。
 *   然后内核在 /sys/bus/iio/devices/iio:device1/ 下生成一堆**普通文件**：
 *
 *     in_accel_x_raw      ← 加速度计 X 轴原始值（有符号整数）
 *     in_accel_y_raw
 *     in_accel_z_raw
 *     in_accel_scale      ← 换算比例：物理量 = raw × scale
 *     in_anglvel_x_raw    ← 陀螺仪（后面接的是角速度 angl(e) vel(ocity)）
 *     ...
 *
 *   于是"读传感器"就退化成了"读文件"：
 *     fopen → fscanf("%d") → fclose
 *   不需要 ioctl、不需要设备树、不需要写驱动。
 *
 *   ★ 关键认知：raw 不是物理量，只是 ADC 的原始计数（LSB）。
 *     本模块故意不换算成 g，因为游戏只需要判"哪边大"，用原始值更省事。
 *
 * =====================================================================
 * 二、功能说明
 * =====================================================================
 *   - 读取 MPU6050 加速度计 X/Y 轴原始值，供体感游戏（2048 倾斜、重力滚球）使用。
 *   - 提供零点校准（把当前水平姿态设为 0）。
 *   - 提供方向修正（INVERT_X/INVERT_Y，解决芯片安装朝向导致的方向相反）。
 *
 * =====================================================================
 * 三、与 sensor.c 的区别
 * =====================================================================
 *   - sensor.c 输出带单位的物理量（g、°/s、lux），供传感器实验室显示；
 *   - imu.c 输出原始整数倾斜值，供体感游戏做方向判断（更简单、更快）。
 *
 * 要看两者的详细对照表，见 imu.h 的文件头。
 */
#include <stdio.h>
#include "imu.h"

/* MPU6050 加速度计 IIO 路径
 * device1 是内核枚举顺序，MPU6050 恰好是第一个 IIO 设备。
 * 如果哪天板子上多了别的 IIO 设备导致编号变了，用
 *    ls /sys/bus/iio/devices/
 * 确认一下实际编号再改这里。 */
#define ACCEL_X_PATH "/sys/bus/iio/devices/iio:device1/in_accel_x_raw"
#define ACCEL_Y_PATH "/sys/bus/iio/devices/iio:device1/in_accel_y_raw"

/* 方向修正：左右/上下反了就把对应项置 1
 *
 * 【为什么需要这个宏】
 *   开发板可能横放也可能竖放，芯片在板子上的焊接朝向也未必和
 *   "屏幕上方"一致，所以物理上"往右倾"在寄存器里可能是负数。
 *   与其在游戏代码里到处写 -tx，不如在这里一次性翻正，
 *   游戏代码就能用最直观的"正值=右"。
 *
 * 实测值：INVERT_X = 1（X 轴需要翻），INVERT_Y = 0（Y 轴不用翻）。
 * 如果发现游戏里方向完全相反，先改这里，不要去改游戏代码。
 *
 * 下面 imu_tilt_x 里的 `INVERT_X ? -v : v` 看着像有运行时分支，
 * 其实 INVERT_X 是字面量常量，编译器会直接把整个三元表达式优化掉，
 * 生成的指令里没有任何判断。 */
#define INVERT_X 1
#define INVERT_Y 0

/* 零点偏移（水平放置时的基准读数）
 *
 * 为什么必须是 static（而不是每次自己读）：
 *   - 校准值要在所有游戏、所有时刻共享；
 *   - 又不想暴露成全局符号（不希望别的 .c 能改它），
 *     所以用文件作用域的 static，外部看不见、但本文件内一直是同一份。
 *
 * 初值 0 表示"还没校准过"，此时行为等价于"原始值直接输出"。
 * 所以没校准时体感游戏会偏，但不会崩 —— 这是有意的降级设计。 */
static int offset_x = 0;
static int offset_y = 0;

/**
 * 读取 sysfs 中的整数原始值。
 *
 * @param path sysfs 文件路径
 * @return 文件里的整数；文件打不开时返回 0
 *
 * 【健壮性说明（成绩答辩可能被问）】
 *   这里刻意写得很"宽容"而不是报错返回：
 *     - fopen 失败 → 返回 0：传感器没接好时游戏会当"没有倾斜"，
 *       表现是游戏卡住不动，但不会崩；
 *     - fscanf 失败 → v 保持初值 0，同样不崩。
 *   代价是**错误被吞掉了**：如果传感器根本不工作，界面上看不出异常，
 *   只能靠串口日志排错。对演示项目来说"不崩"比"精确报错"更重要。
 */
static int read_raw(const char *path)
{
    FILE *fp = fopen(path, "r");
    if(!fp) return 0;                       /* 打不开就当 0，不报错 */
    int v = 0;
    fscanf(fp, "%d", &v);                   /* sysfs 里的值都是十进制文本 */
    fclose(fp);                             /* 必须关，否则 fd 会泄漏（长时间运行会耗尽 1024 个 fd） */
    return v;
}

/**
 * 校准：把当前水平姿态的读数作为零点（取 10 次平均降抖动）。
 *
 * 【为什么是 10 次平均】
 *   MPU6050 静止时输出仍有几十 LSB 的随机噪声。
 *   只采 1 次，offset 就带着这份噪声，之后每个倾斜值都恒定偏一点。
 *   连续采 10 次求和取平均，随机噪声按 1/√10 衰减，零点就稳了。
 *
 * 【累计和为什么用 long 而不是 int】
 *   raw 值量级约 ±16000，10 次求和最大约 ±160000。
 *   虽然在 int 范围内，但用 long 明确表达"这是个中间累加量、
 *   不希望溢出"，读代码的人一眼就知道。
 *
 * 【必须在水平静止时调用】
 *   本函数无条件把"当前读数"当作零点。如果此刻板子是歪的，
 *   那么"歪"就变成了"水平"，之后所有方向判断都会系统性偏移。
 *   所以设置页的按钮旁应该提示用户先把板子放平。
 */
void imu_calibrate(void)
{
    long sx = 0, sy = 0;
    for(int i = 0; i < 10; i++) {
        sx += read_raw(ACCEL_X_PATH);
        sy += read_raw(ACCEL_Y_PATH);
    }
    offset_x = (int)(sx / 10);              /* 除以 10 得平均；显式 (int) 转换表明是有意缩窄 */
    offset_y = (int)(sy / 10);
    printf("[imu] 校准完成 offset=(%d, %d)\n", offset_x, offset_y);   /* 串口日志，方便排错 */
}

/**
 * X 轴倾斜值：减零点 + 方向修正。
 *
 * 执行顺序（先减后翻，不能颠倒）：
 *   raw - offset   → 消除装配误差和温漂，水平时得到 0
 *   再按 INVERT_X 取反 → 让"往右倾"对应正值
 *
 * 如果先翻再减，offset 也得跟着翻，逻辑更容易写错。
 *
 * 注意：这是"单次采样"，没有滤波 —— 游戏要的就是即时响应。
 *       如果发现抖动导致误触，应该在**游戏侧**加死区（阈值），
 *       而不是在这里加滤波，否则操作会有延迟感。
 */
int imu_tilt_x(void)
{
    int v = read_raw(ACCEL_X_PATH) - offset_x;
    return INVERT_X ? -v : v;
}

/* Y 轴倾斜值：减零点 + 方向修正（与 X 轴完全对称） */
int imu_tilt_y(void)
{
    int v = read_raw(ACCEL_Y_PATH) - offset_y;
    return INVERT_Y ? -v : v;
}
