/**
 * @file    ball.h
 * @brief   重力滚球游戏界面接口声明
 *
 * =====================================================================
 * 一、玩法
 * =====================================================================
 *   倾斜开发板控制小球在屏幕上滚动：
 *     滚进 绿色圆环 = 胜利
 *     滚进 红色陷阱 = 失败（4 个陷阱，每次进入随机生成位置）
 *   结束后弹出提示和「重新开始」按钮，重开时圆环重新随机。
 *
 * =====================================================================
 * 二、它是怎么"体感"的
 * =====================================================================
 *   用 imu.h 的 imu_tilt_x() / imu_tilt_y() 拿到倾斜值，
 *   当作"重力加速度"累加到小球速度上（见 ball.c 的 game_loop_cb）：
 *       速度 += 倾斜值 × 系数   （倾斜越大，加速越猛）
 *       速度 ×= 摩擦系数        （松手后慢慢停）
 *       位置 += 速度
 *   撞到屏幕边界则速度反向并减半，模拟能量损失。
 *
 *   ★ 所以这个游戏**必须先用 imu_calibrate() 校准**（设置页的「校准」按钮，
 *     或进"传感器实验室"会自动校准一次），
 *     否则小球会一直往一个方向飘 —— 这是最常见的问题。
 *
 * =====================================================================
 * 三、依赖模块
 * =====================================================================
 *   imu.h          读倾斜值
 *   game_center.h  返回游戏中心（返回时调 ui_select_game_screen）
 *
 * =====================================================================
 * 四、屏幕指针的生命周期（和 game_center 的配合）
 * =====================================================================
 *   ball_screen 由 ui_ball_init() 创建并赋值，
 *   由本模块自己的返回回调（to_game_center_cb）删除并置 NULL。
 *
 *   同时 game_center.c 的 to_ball_screen_cb 也会**读取**这个指针：
 *   它是懒创建的（== NULL 才调 ui_ball_init），
 *   所以本模块的返回回调必须把它置回 NULL，
 *   否则下次从游戏中心进滚球时会拿一个已释放的地址去 lv_screen_load → 崩溃。
 */
#ifndef __BALL_H__
#define __BALL_H__

/* 重力滚球屏幕对象（全局）。
 * 跨文件共享：本模块创建/删除，game_center.c 读取判断是否要重新创建。 */
extern lv_obj_t * ball_screen;   // 重力滚球屏幕对象（全局）

/**
 * 创建并返回重力滚球屏幕对象。
 *
 * 做了这些事：
 *   1. 取 4 档中文字体（24 标题 / 36 结束提示 / 20 按钮 / 14 小字）；
 *   2. srand(time(NULL)) 播种随机数（决定圆环位置，每次进来都不一样）；
 *   3. 创建终点圆环、4 个陷阱圆环、小球、结果标签、重开按钮；
 *   4. randomize_circles() 随机生成位置，apply_circle_pos() 摆到界面上；
 *   5. 创建游戏循环定时器（**10ms** 周期，约 100fps）；
 *   6. lv_screen_load(scr) 切到本屏，并把屏幕存进 ball_screen。
 *
 * 副作用警告：内部已经 lv_screen_load()，调用方不需要再切屏。
 * 重复调用会创建第二屏且旧的没人删，调用方应先判 NULL。
 *
 * @return 新建的屏幕对象
 */
lv_obj_t * ui_ball_init(void);

#endif
