/**
 * @file    sensor_lab.h
 * @brief   传感器实验室界面接口声明
 *
 * =====================================================================
 * 一、这个界面展示什么
 * =====================================================================
 *   把两个传感器的数据"可视化"，让评委一眼看到硬件在真实工作：
 *
 *     左侧  俯仰角 Pitch 仪表条（绿）    -90° ~ +90°，对称模式，中间为 0
 *     左侧  横滚角 Roll  仪表条（橙）    同上
 *     右侧  加速度三轴实时折线图          ax 红 / ay 绿 / az 蓝，±2g
 *     底部  照度仪表条（蓝） + 三轴加速度/陀螺仪数值
 *
 *   刷新周期 200ms（5Hz）—— 够平滑，也不会让 LVGL 太忙。
 *
 * =====================================================================
 * 二、为什么这个界面有价值（答辩可以这么讲）
 * =====================================================================
 *   其他模块（游戏、聊天室）都是"用掉"传感器数据就完了，
 *   只有这里把**原始数据直接呈现**出来，可以：
 *     - 现场验证传感器接线/驱动是否正常（数值在动 = 正常）；
 *     - 在验收时演示"倾斜板子 → 曲线跟着变 → 姿态角跟着变"，
 *       比嘴上说"我用了 MPU6050"有说服力得多；
 *     - 排错时用 —— 游戏方向不对？先来这里看 ax/ay 的正负号。
 *
 * =====================================================================
 * 三、和 sensor.c 的分工
 * =====================================================================
 *   sensor_lab.c（本界面）负责"显示"
 *   sensor.c             负责"读数据"
 *   本界面每 200ms 调一次 sensor.c 的取值函数，然后画到控件上。
 *
 * =====================================================================
 * 四、进入时会发生什么（注意副作用）
 * =====================================================================
 *   ui_sensor_lab_init() 里会调用：
 *     sensor_init()       读量程比例因子（必须，否则数值差几十倍）
 *     sensor_calibrate()  零点校准 —— ★ 所以**进入本页时板子必须水平**！
 *
 *   也就是说"进实验室"这个动作会重置体感零点。
 *   如果用户歪着拿板子进来，出去后玩游戏的方向就会偏，
 *   需要去设置页重新点一次「校准」。这是已知的体验缺陷。
 *
 * =====================================================================
 * 五、屏幕指针的生命周期
 * =====================================================================
 *   sensor_lab_screen 进来创建、点返回时删除并置 NULL。
 *   返回时同时删掉刷新定时器（顺序：删定时器 → 切屏 → 删屏）。
 */
#ifndef __SENSOR_LAB_H__
#define __SENSOR_LAB_H__

/* 传感器实验室屏。
 * 由 ui_sensor_lab_init 赋值，由返回回调删除并置 NULL。 */
extern lv_obj_t * sensor_lab_screen;   // 传感器实验室屏（全局）

/**
 * 创建并返回传感器实验室屏幕对象。
 *
 * 做了这些事：
 *   1. 取 3 档中文字体（24 标题 / 18 正文 / 14 小字）；
 *   2. sensor_init() + sensor_calibrate()（★ 会重置体感零点）；
 *   3. 创建仪表条、折线图、数值标签，全部指针存进**模块内 static 全局**
 *      （因为 200ms 定时器回调要更新它们）；
 *   4. 创建 200ms 刷新定时器；
 *   5. lv_screen_load(scr) 切到本屏，并把屏幕存进 sensor_lab_screen。
 *
 * 副作用警告：内部已经 lv_screen_load()，调用方不需要再切屏。
 * 重复调用会创建第二屏且旧的没人删，调用方应先判 NULL。
 *
 * @return 新建的屏幕对象
 */
lv_obj_t * ui_sensor_lab_init(void);

#endif
