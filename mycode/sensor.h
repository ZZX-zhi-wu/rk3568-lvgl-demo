/**
 * @file    sensor.h
 * @brief   传感器数据层接口声明（MPU6050 六轴 + BH1750 照度）
 *
 * =====================================================================
 * 一、这个模块是干什么的
 * =====================================================================
 *   把板子上两个传感器包装成几个简单的取值函数：
 *     MPU6050 → 加速度三轴(g) + 陀螺仪三轴(°/s) + 姿态角(°)
 *     BH1750  → 环境光照度(lux)
 *   供「传感器实验室」界面实时显示，也是设置页自动亮度的数据来源。
 *
 * =====================================================================
 * 二、和 imu.c 的分工（别搞混）
 * =====================================================================
 *   sensor.c → 输出**带单位的物理量**，给人看的（界面显示）
 *   imu.c    → 输出**原始整数倾斜值**，给游戏判方向的
 *   要显示数值就用本模块；要判"往哪边倒"就用 imu.h。
 *
 * =====================================================================
 * 三、单位约定（答辩常问，记牢）
 * =====================================================================
 *   加速度  单位 g   （1 g = 9.81 m/s²）—— 水平静置时 az ≈ +1.0
 *   陀螺仪  单位 °/s （度每秒）
 *   姿态角  单位 °   （水平 = 0°）
 *   照度    单位 lux
 *
 * =====================================================================
 * 四、本头文件不依赖 LVGL
 * =====================================================================
 *   纯 C 接口，可在 PC 上单独编译测试。
 *
 * =====================================================================
 * 五、正确的调用顺序（顺序错了数值就是错的）
 * =====================================================================
 *     sensor_init();        // ① 进实验室时调一次：读量程比例因子
 *     sensor_calibrate();   // ② 板子水平放好，再调：把当前姿态记作零点
 *     ... 此后每 100ms 左右调取值函数 ...
 *     float ax = sensor_accel_x();
 *     float gz = sensor_gyro_z();
 *
 * =====================================================================
 * 六、一个容易踩的坑：取值函数有"副作用"
 * =====================================================================
 *   sensor_accel_x/y/z 内部维护低通滤波状态，**每调用一次滤波就往前走一步**。
 *   所以：
 *     - 不要在同一个周期里重复调用同一个函数（比如既显示又判断，
 *       应该先存进局部变量再复用）；
 *     - 调用频率变了，滤波的等效平滑程度也会变。
 *   另外：sensor_accel_* 和 sensor_pitch_roll 读的都是加速度，
 *   而 sensor_pitch_roll 内部会自己再读一遍（共 3 次），
 *   如果调用方已经读好了 ax/ay/az，建议照公式自己算，省 3 次文件读。
 */
#ifndef __SENSOR_H__
#define __SENSOR_H__

/**
 * 初始化：从 sysfs 读回两个量程比例因子并缓存。
 *
 * MPU6050 支持多档量程（±2g/±4g/±8g/±16g、±250/±500/±1000/±2000°/s），
 * 不同量程下 1 个 LSB 代表的物理量不同，内核已经把当前档位对应的
 * 比例写在了 in_accel_scale / in_anglvel_scale 里。
 * 从文件读比在代码里写死更稳 —— 改量程时代码不用动。
 *
 * 只在进入传感器实验室时调一次即可（值不会自己变）。
 */
void sensor_init(void);

/**
 * 零点校准：把当前姿态的读数记为零点偏移，并清空低通滤波状态。
 *
 * 必须在【水平静止】时调用。做三件事：
 *   1. ax / ay 记为零点（消除安装倾斜和温漂）；
 *   2. 陀螺仪三轴记为零点（静止时角速度应为 0，实测有个小偏置）；
 *   3. Z 轴**故意不校准**（off_az = 0），保留重力分量，
 *      否则水平时 az 会变成 0，姿态角就没法算了。
 *
 * 注意：本函数只采 1 次样本，没有像 imu_calibrate() 那样取 10 次平均。
 *       偶发噪声可能让它偏几十毫伏，界面数值会略微漂。
 *       要更稳就连续校两三次（每次间隔一下读值）。
 */
void sensor_calibrate(void);

/**
 * 加速度 X 轴，单位 g。
 * 内部：raw - 零点 → × accel_scale → ÷ 9.81 → 一阶低通滤波
 * @return 已滤波的加速度值；水平静置时该轴接近 0（已校准）
 */
float sensor_accel_x(void);

/** 加速度 Y 轴，单位 g（同 X 轴的处理流程） */
float sensor_accel_y(void);

/**
 * 加速度 Z 轴，单位 g。
 * @return 水平静置时约为 +1.0 g（这就是重力分量，因为 Z 轴不做零点校准）
 */
float sensor_accel_z(void);

/**
 * 陀螺仪 X 轴，单位 °/s。
 * 内部：raw - 零点 → × gyro_scale → × 180/π
 *
 * ★ 注意单位链：内核给的 anglvel_scale 是 **rad/s per LSB**（弧度每秒），
 *   必须再乘 180/π 才是度每秒。少了这一步数值会差 57 倍，
 *   这是接陀螺仪最常见的单位错误。
 */
float sensor_gyro_x(void);

/** 陀螺仪 Y 轴，单位 °/s */
float sensor_gyro_y(void);

/** 陀螺仪 Z 轴，单位 °/s（绕垂直轴转，即"左右旋转"） */
float sensor_gyro_z(void);

/**
 * 用加速度计解算姿态角（水平 = 0°）。
 *
 * 原理：加速度计在静止时测到的就是重力向量，由重力在三个轴上的
 *       分量比例反推板子的倾斜角度。公式：
 *         pitch（俯仰，前后倾）= atan2(-ay, √(ax²+az²))
 *         roll （横滚，左右倾）= atan2( ax, √(ay²+az²))
 *       用 atan2 而不是 atan 的原因：atan 在分母为 0 时会炸，
 *       而且区分不了象限；atan2 两者都处理好了。
 *       分母取"另外两轴的合成模长"是为了让角度在 -90°~+90° 内单调。
 *
 * @param pitch 输出：俯仰角（度）。是一个输出指针，不能传 NULL —— 内部会直接解引用写入。
 * @param roll  输出：横滚角（度）、同上，不能传 NULL。
 *
 * 开销提醒：内部会调用 3 次 sensor_accel_*，也就是 3 次文件读 + 3 次滤波推进。
 *           调用方若已经读过 ax/ay/az，建议按上面的公式自己算。
 */
void sensor_pitch_roll(float *pitch, float *roll);

/**
 * 读取环境光照度，单位 lux。
 *
 * 优先读 in_illuminance_input（内核已换算好的 lux 值）；
 * 读不到时退而求其次，用 in_illuminance_raw × in_illuminance_scale 自己算。
 * 两条路都失败则返回 0。
 *
 * 典型量级：白天室内 100~600 lux，晚上关灯 0~10 lux，强光下几千。
 */
int sensor_illuminance(void);

#endif
