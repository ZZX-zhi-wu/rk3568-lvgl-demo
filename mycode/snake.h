/**
 * @file    snake.h
 * @brief   体感贪吃蛇接口声明
 *
 * =====================================================================
 * 一、玩法
 * =====================================================================
 *   12×12 网格棋盘，蛇每 300ms 自动走一步：
 *     吃到红色食物 → 蛇变长，重新随机生成食物
 *     撞墙或撞到自己 → 游戏结束，弹出「重新开始」
 *
 *   两种控制模式（**开始前二选一，过程中不能切换**）：
 *     ① 体感模式：倾斜开发板改变方向（每 150ms 读一次倾斜值）
 *     ② 按键模式：点屏幕右侧的「上/下/左/右」四个方向键
 *
 *   为什么锁定模式：两种输入源同时生效会互相打架 ——
 *   体感定时器刚把方向设成"右"，用户又点了一下"上"，
 *   下一拍体感又按倾斜值覆盖回去，玩家会觉得"按钮失灵"。
 *   所以选定模式后**直接把另一种输入禁用**（体感模式禁用方向键，
 *   按键模式则不创建体感定时器）。
 *
 * =====================================================================
 * 二、对外提供
 * =====================================================================
 *   - ui_snake_init()：创建贪吃蛇界面并返回屏幕对象。
 *   - snake_screen：贪吃蛇屏幕全局指针（供 game_center.c 跳转和删除时使用）。
 *
 * =====================================================================
 * 三、屏幕指针的生命周期（和 game_center 的配合）
 * =====================================================================
 *   snake_screen 由 ui_snake_init() 创建并赋值，
 *   由本模块的 to_game_center_cb() 删除并置 NULL。
 *
 *   ★ 必须置 NULL：game_center.c 的 to_snake_screen_cb 是懒创建的
 *     （`if(snake_screen == NULL) 创建`），
 *     不置 NULL 下次进来就会拿已释放的地址去 lv_screen_load → 崩溃。
 *
 * =====================================================================
 * 四、体感控制用的是加速度计，不是陀螺仪
 * =====================================================================
 *   imu.c 读的是 in_accel_x_raw / in_accel_y_raw（加速度计）。
 *   判断"板子往哪边倾"靠的是重力方向在 X/Y 轴上的分量，
 *   这是加速度计的能力；陀螺仪测的是"转得多快"（角速度），
 *   静止倾斜时陀螺仪读数是 0，根本判不出倾角。
 *   （旧注释里写的"读取陀螺仪倾斜值"是错的，已在下方修正。）
 */
#ifndef __SNAKE_H__
#define __SNAKE_H__

/* 贪吃蛇屏幕全局指针。
 * 本模块创建/删除，game_center.c 读取它判断是否需要重新创建。 */
extern lv_obj_t * snake_screen;

/**
 * 创建并返回贪吃蛇屏幕对象。
 *
 * 做了这些事：
 *   1. 取 4 档中文字体（24 标题 / 18 正文 / 36 结束大字 / 14 小字）；
 *   2. srand(time(NULL)) 播种随机数（决定食物位置）；
 *   3. 创建 12×12 = 144 个方块控件 + 4 个方向键 + 模式选择 UI；
 *   4. init_snake() 初始化蛇身（3 节，头在 (5,5)）并生成第一个食物；
 *   5. 创建移动定时器（**300ms** 一步）；
 *      ★ 体感定时器**不在这里创建**，等用户选了「体感模式」才启动；
 *   6. lv_screen_load(scr) 切到本屏，并把屏幕存进 snake_screen。
 *
 * 副作用警告：内部已经 lv_screen_load()，调用方不需要再切屏。
 * 重复调用会创建第二屏且旧的没人删，调用方应先判 NULL。
 *
 * @return 新建的屏幕对象
 */
lv_obj_t * ui_snake_init(void);

#endif
