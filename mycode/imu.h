/**
 * @file    imu.h
 * @brief   IMU 数据层接口声明（体感游戏用）
 *
 * =====================================================================
 * 一、这个模块是干什么的
 * =====================================================================
 *   读 MPU6050 加速度计的 X/Y 两轴，输出「倾斜值」整数，
 *   给体感游戏判断"板子往哪边倒了"，从而决定游戏里的操作方向。
 *
 * =====================================================================
 * 二、和 sensor.c 的区别（最容易混，先分清）
 * =====================================================================
 *   ┌──────────┬─────────────────────────┬─────────────────────────┐
 *   │          │ imu.c（本模块）         │ sensor.c                │
 *   ├──────────┼─────────────────────────┼─────────────────────────┤
 *   │ 输出     │ int 原始倾斜值          │ float 物理量(g、°/s、lux)│
 *   │ 用途     │ 体感游戏判方向          │ 传感器实验室显示数值    │
 *   │ 轴向     │ 只用 X / Y 两轴         │ X/Y/Z + 陀螺仪 + 光照   │
 *   │ 滤波     │ 无（游戏要的就是即时）  │ 一阶低通滤波去抖        │
 *   │ 返回值   │ 正负号即方向            │ 带单位、带小数          │
 *   └──────────┴─────────────────────────┴─────────────────────────┘
 *   要"看数值"用 sensor.c；要"判方向"用 imu.c。
 *
 * =====================================================================
 * 三、本头文件不依赖 LVGL
 * =====================================================================
 *   纯 C 接口，可以在 PC 上用 gcc 单独编译测试，不需要板子和屏幕。
 *
 * =====================================================================
 * 四、典型用法（游戏里的每一拍）
 * =====================================================================
 *     int tx = imu_tilt_x();     // 往右倾 → 正值，往左倾 → 负值
 *     int ty = imu_tilt_y();
 *     if(tx >  3000) 往右移动();
 *     if(tx < -3000) 往左移动();
 *
 *   阈值取多少要实测：校准后水平静置读数接近 0，
 *   倾斜 30° 左右大约 5000~8000，所以 3000 上下的死区比较合适。
 */
#ifndef __IMU_H__
#define __IMU_H__

/**
 * 读取 X 轴倾斜值。内部做了两件事：
 *   1. 减去零点偏移（offset_x）—— 所以水平放置时读数≈0；
 *   2. 方向修正（imu.c 里的 INVERT_X 宏）—— 芯片装反了也能改回来。
 *
 * @return 有符号整数；正负代表两个相反方向，绝对值 ≈ 倾斜程度。
 *         注意：sysfs 读失败时内部 read_raw() 返回 0，
 *         于是本函数会返回 -offset_x（看起来像一个微小的"倾斜"），
 *         不会崩，但也不要把它当成有效数据用。
 *
 * 开销：每次调用都要 fopen/fscanf/fclose 一次 sysfs 文件（约几十微秒）。
 *       游戏里每 30~50ms 调一次没问题，别放在死循环里疯狂调。
 */
int imu_tilt_x(void);

/**
 * 读取 Y 轴倾斜值。和 imu_tilt_x 完全对称，只是换了轴和方向修正宏。
 * @return 有符号整数，含义同上
 */
int imu_tilt_y(void);

/**
 * 校准：把当前姿态的读数记为零点。
 *
 * 内部连读 10 次取平均（降抖动），结果存进 offset_x / offset_y。
 * 必须在【开发板水平静止放置】时调用，否则会把歪着的姿态当成"水平"，
 * 之后所有体感方向都会偏 —— 这是体感游戏"方向不听使唤"最常见的原因。
 *
 * 什么时候调用：
 *   - 设置页的「校准」按钮（settings.c 的 calibrate_cb）；
 *   - 游戏中心里提示用户"水平放置 2 秒"后再调。
 *
 * 注意：本函数在 LVGL 主线程里同步执行（10 次文件读，几百微秒），
 *       不会造成卡顿，可以放心直接在按钮回调里调。
 */
void imu_calibrate(void);

#endif
